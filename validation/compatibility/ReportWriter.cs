using System.Globalization;
using System.Text;
using System.Text.Json;

namespace CompatibilityValidation;

/// <summary>Turns the reports and timings of all codec versions into one readable comparison.</summary>
internal static class ReportWriter
{
    private const string LocalVersion = "local";
    private const string ComparedManagedVersion = "2.0.0";

    internal static void Write(string resultsDirectory, string outputPath)
    {
        var reports = Directory.GetFiles(resultsDirectory, "report-*.json")
            .Select(ReadReport)
            .OrderBy(report => report.CodecVersion == LocalVersion)
            .ThenBy(report => report.CodecVersion, StringComparer.Ordinal)
            .ToArray();
        var localReport = reports.Single(report => report.CodecVersion == LocalVersion);
        var markdown = new StringBuilder();

        markdown.AppendLine("# Compatibility and performance measurement");
        markdown.AppendLine();
        markdown.AppendLine("Generated by `validation/compatibility/run.sh`. Do not edit by hand.");
        markdown.AppendLine();

        AppendVersions(markdown, reports);
        AppendFormat(markdown, reports, localReport);
        AppendManaged(markdown, reports, localReport);
        AppendBehaviors(markdown, reports, localReport);
        AppendPerformance(markdown, Path.Combine(resultsDirectory, "performance.jsonl"));

        File.WriteAllText(outputPath, markdown.ToString());
    }

    private static CompatibilityReport ReadReport(string path)
    {
        var reportJson = File.ReadAllText(path);

        return JsonSerializer.Deserialize<CompatibilityReport>(reportJson)
            ?? throw new InvalidDataException($"Report '{path}' is empty.");
    }

    private static void AppendVersions(StringBuilder markdown, CompatibilityReport[] reports)
    {
        markdown.AppendLine("## Measured versions");
        markdown.AppendLine();
        markdown.AppendLine("| Version | Runtime | JIT optimizer disabled | Assembly SHA-256 |");
        markdown.AppendLine("|---|---|---|---|");

        foreach (var report in reports)
        {
            markdown.AppendLine(
                $"| {report.CodecVersion} | {report.Runtime} | {report.JitOptimizerDisabled} | `{report.CodecAssemblySha256}` |");
        }

        markdown.AppendLine();
    }

    private static void AppendFormat(StringBuilder markdown, CompatibilityReport[] reports, CompatibilityReport localReport)
    {
        markdown.AppendLine("## Stored shard format");
        markdown.AppendLine();
        markdown.AppendLine("Parity is compared with the local codec by SHA-256. Recovery uses each version's buffer API.");
        markdown.AppendLine();
        markdown.AppendLine("| Version | Cases | Parity identical to local | Loss patterns | Restored |");
        markdown.AppendLine("|---|---:|---:|---:|---:|");

        var localHashes = localReport.Formats.ToDictionary(format => format.Case, format => format.ParityHash);

        foreach (var report in reports)
        {
            var identicalCount = report.Formats.Count(format => localHashes[format.Case] == format.ParityHash);
            var lossPatternCount = report.Formats.Sum(format => format.LossPatternCount);
            var restoredCount = report.Formats.Sum(format => format.RestoredPatternCount);

            markdown.AppendLine(
                $"| {report.CodecVersion} | {report.Formats.Length} | {identicalCount} | {lossPatternCount} | {restoredCount} |");
        }

        markdown.AppendLine();
    }

    private static void AppendManaged(StringBuilder markdown, CompatibilityReport[] reports, CompatibilityReport localReport)
    {
        var publishedReport = reports.Single(report => report.CodecVersion == ComparedManagedVersion);
        var localHashes = localReport.ManagedCases.ToDictionary(managedCase => managedCase.Case, managedCase => managedCase.ShardsHash);

        markdown.AppendLine("## Allocating API");
        markdown.AppendLine();
        markdown.AppendLine("Shards of the allocating encoder compared with the local codec. Version 1.0.0 has no such encoder.");
        markdown.AppendLine();
        markdown.AppendLine("| Version | Cases | Shards identical to local |");
        markdown.AppendLine("|---|---:|---:|");

        foreach (var report in reports.Where(report => report.ManagedCases.Length != 0))
        {
            var identicalCount = report.ManagedCases.Count(managedCase => localHashes[managedCase.Case] == managedCase.ShardsHash);

            markdown.AppendLine($"| {report.CodecVersion} | {report.ManagedCases.Length} | {identicalCount} |");
        }

        markdown.AppendLine();
        markdown.AppendLine("Recovery through the unsigned allocating decoder:");
        markdown.AppendLine();
        markdown.AppendLine("| Version | Loss patterns | Payload restored | Rejected with an exception | Wrong bytes |");
        markdown.AppendLine("|---|---:|---:|---:|---:|");

        foreach (var report in new[] { publishedReport, localReport })
        {
            var lossPatternCount = report.ManagedCases.Sum(managedCase => managedCase.LossPatternCount);
            var restoredCount = report.ManagedCases.Sum(managedCase => managedCase.RestoredPatternCount);
            var rejectedCount = report.ManagedCases.Sum(managedCase => managedCase.RejectedPatternCount);
            var wrongCount = lossPatternCount - restoredCount - rejectedCount;

            markdown.AppendLine($"| {report.CodecVersion} | {lossPatternCount} | {restoredCount} | {rejectedCount} | {wrongCount} |");
        }

        markdown.AppendLine();
    }

    private static void AppendBehaviors(StringBuilder markdown, CompatibilityReport[] reports, CompatibilityReport localReport)
    {
        var publishedReport = reports.Single(report => report.CodecVersion == ComparedManagedVersion);
        var localObservations = localReport.Behaviors.ToDictionary(behavior => behavior.Scenario, behavior => behavior.Observation);

        markdown.AppendLine("## Caller-visible behavior");
        markdown.AppendLine();
        markdown.AppendLine($"| Scenario | {ComparedManagedVersion} | Current | Same |");
        markdown.AppendLine("|---|---|---|---|");

        foreach (var behavior in publishedReport.Behaviors)
        {
            var localObservation = localObservations[behavior.Scenario];
            var isSame = localObservation == behavior.Observation ? "yes" : "**no**";

            markdown.AppendLine($"| {behavior.Scenario} | {behavior.Observation} | {localObservation} | {isSame} |");
        }

        markdown.AppendLine();
    }

    private static void AppendPerformance(StringBuilder markdown, string performancePath)
    {
        if (File.Exists(performancePath) == false)
        {
            return;
        }

        var measurements = File.ReadLines(performancePath)
            .Select(line => JsonSerializer.Deserialize<PerformanceResult>(line)!)
            .ToArray();
        var cells = measurements
            .GroupBy(measurement => (measurement.Operation, measurement.PayloadBytes))
            .OrderBy(cell => cell.Key.PayloadBytes)
            .ThenBy(cell => cell.Key.Operation, StringComparer.Ordinal);

        markdown.AppendLine("## Performance");
        markdown.AppendLine();
        markdown.AppendLine("10 data and 2 parity shards, one logical processor, default codec settings. Each value is");
        markdown.AppendLine("the median over fresh processes of each process's median batch. The range shows the");
        markdown.AppendLine("fastest and slowest process. Allocation is per operation in the same processes.");
        markdown.AppendLine();
        markdown.AppendLine($"| Payload bytes | Operation | {ComparedManagedVersion} ms (range) | {ComparedManagedVersion} allocated | Current ms (range) | Current allocated | Speedup |");
        markdown.AppendLine("|---:|---|---:|---:|---:|---:|---:|");

        foreach (var cell in cells)
        {
            var published = cell.Where(measurement => measurement.CodecVersion == ComparedManagedVersion).ToArray();
            var current = cell.Where(measurement => measurement.CodecVersion == LocalVersion).ToArray();
            var speedup = Median(published) / Median(current);

            markdown.AppendLine(
                string.Create(
                    CultureInfo.InvariantCulture,
                    $"| {cell.Key.PayloadBytes} | {cell.Key.Operation} | {Describe(published)} | {DescribeAllocation(published)} | {Describe(current)} | {DescribeAllocation(current)} | {speedup:F1}x |"));
        }

        markdown.AppendLine();
    }

    private static string Describe(PerformanceResult[] measurements)
    {
        var fastest = measurements.Min(measurement => measurement.MedianMilliseconds);
        var slowest = measurements.Max(measurement => measurement.MedianMilliseconds);

        return $"{FormatMilliseconds(Median(measurements))} ({FormatMilliseconds(fastest)} to {FormatMilliseconds(slowest)})";
    }

    private static string FormatMilliseconds(double milliseconds)
    {
        // Values below one millisecond keep three significant digits instead of rounding small payloads to 0.001.
        var format = milliseconds < 1 ? "G3" : "F3";

        return milliseconds.ToString(format, CultureInfo.InvariantCulture);
    }

    private static string DescribeAllocation(PerformanceResult[] measurements)
    {
        var allocations = measurements
            .Select(measurement => measurement.AllocatedBytesPerOperation)
            .Order()
            .ToArray();

        return allocations[allocations.Length / 2].ToString(CultureInfo.InvariantCulture);
    }

    private static double Median(PerformanceResult[] measurements)
    {
        var milliseconds = measurements
            .Select(measurement => measurement.MedianMilliseconds)
            .Order()
            .ToArray();

        return milliseconds[milliseconds.Length / 2];
    }
}
